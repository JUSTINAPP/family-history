import assert from "node:assert/strict";
export async function conversationChecks({q, asUser, asOwner, denied, users, archive, otherArchive, manifestFile}) {
  let checks = 0;
  const eq = (a,b) => {assert.deepEqual(a,b); checks++;};
  const one = async (sql,args=[]) => (await q(sql,args)).rows[0];
  await asUser(users[3]);
  const item = (await one("select public.begin_ingestion($1,gen_random_uuid(),'Photograph, still to be catalogued','Photograph','','{}',$2::jsonb) id", [archive, JSON.stringify([manifestFile])])).id;
  for (const f of (await q("select * from public.archive_item_files where item_id=$1",[item])).rows)
    await q("insert into storage.objects(bucket_id,name,metadata) values($1,$2,$3::jsonb)",[f.bucket_id,f.storage_path,JSON.stringify({size:f.byte_size,mimetype:f.mime_type})]);
  await q("select public.complete_ingestion($1,$2)",[archive,item]);
  const field="select public.save_item_field($1,$2,$3,$4,$5,$6::jsonb)", post="select public.post_item_comment($1,$2,$3,$4,$5) id";
  let before={value:"",precision:"unknown"};
  for (const [value,precision] of [["1984","approximate"],["1980s","decade"],["1984-03","month"],["1984-03-12","exact"],["1984","year"],["","unknown"]]) {
    await q(field,[archive,item,"date",value,precision,JSON.stringify(before)]);
    eq(await one("select reported_date, date_precision from public.archive_items where id=$1",[item]),{reported_date:value,date_precision:precision});
    before={value,precision};
  }
  await denied(field,[archive,item,"date","1984-02-31","exact",JSON.stringify(before)]);
  await denied(field,[archive,item,"date","1984-13","month",JSON.stringify(before)]);
  await denied(field,[archive,item,"date","1979","approximate",JSON.stringify({value:"stale",precision:"unknown"})]);
  await q(field,[archive,item,"caption","Our afternoon","unknown",JSON.stringify({value:"Photograph, still to be catalogued"})]);
  eq((await one("select title from public.archive_items where id=$1",[item])).title,"Our afternoon");
  eq((await one("select count(*)::int n from public.recollections where item_id=$1",[item])).n,0);
  const write="72000000-0000-4000-8000-000000000001";
  const root=(await one(post,[archive,item,"Was this Auroville?",null,write])).id;
  eq((await one(post,[archive,item,"Was this Auroville?",null,write])).id,root);
  await denied(post,[archive,item,"Different retry",null,write]);
  await asUser(users[4]);
  const reply=(await one(post,[archive,item,"Yes, outside our house.",root,"72000000-0000-4000-8000-000000000002"])).id;
  const records=(await q("select author_id,parent_id,created_at from public.comments where item_id=$1 order by created_at,id",[item])).rows;
  eq(records.length,2); eq(records[0].author_id,users[3]); eq(records[1].author_id,users[4]); eq(records[1].parent_id,root); eq(!!records[0].created_at,true);
  await denied(post,[archive,item,"Too deep",reply,"72000000-0000-4000-8000-000000000003"]);
  const change="select public.change_item_comment($1,$2,$3,$4)";
  await denied(change,[root,"edit","Overwrite someone else",1]);
  await asUser(users[3]);
  await q(change,[root,"edit","Was this Auroville in 1979?",1]);
  eq((await one("select revision from public.comments where id=$1",[root])).revision,2);
  eq(!!(await one("select edited_at from public.comments where id=$1",[root])).edited_at,true);
  await denied(change,[root,"edit","stale write",1]);
  await denied(change,[reply,"edit","Other's words",1]);
  await denied(change,[root,"archive","",2]);
  await denied("update public.comments set body='forged' where id=$1",[root]);
  await denied("select public.promote_item_comment($1,2)",[root]);
  await asUser(users[4]);
  await denied("select public.promote_item_comment($1,1)",[root]);
  const recollection=(await one("select public.promote_item_comment($1,2) id",[root])).id;
  eq((await one("select public.promote_item_comment($1,2) id",[root])).id,recollection);
  const copied=await one("select contributor_id,original_text,recorded_at from public.recollections where id=$1",[recollection]);
  eq(copied.contributor_id,users[3]); eq(copied.original_text,"Was this Auroville in 1979?"); eq(copied.recorded_at,records[0].created_at);
  eq((await one("select count(*)::int n from public.comments where item_id=$1",[item])).n,2);
  await q(change,[root,"archive","",2]);
  await asOwner();
  const previousRole=(await one("select role from public.archive_memberships where archive_id=$1 and profile_id=$2",[archive,users[2]])).role;
  await q("update public.archive_memberships set role='viewer' where archive_id=$1 and profile_id=$2",[archive,users[2]]);
  await asUser(users[2]);
  eq((await one("select count(*)::int n from public.comments where id=$1",[root])).n,0);
  eq((await one("select count(*)::int n from public.comments where id=$1",[reply])).n,1);
  eq((await one("select count(*)::int n from public.provenance where item_id=$1 and field_path like 'comment_%'",[item])).n,0);
  await denied(post,[archive,item,"Viewer write",null,"72000000-0000-4000-8000-000000000004"]);
  await denied(field,[archive,item,"date","1984","year",JSON.stringify(before)]);
  await asUser(users[1]);
  eq((await one("select count(*)::int n from public.comments where item_id=$1",[item])).n,0);
  await denied(post,[archive,item,"Foreign archive",null,"72000000-0000-4000-8000-000000000005"]);
  await denied(post,[otherArchive,item,"Mismatch",null,"72000000-0000-4000-8000-000000000006"]);
  await denied("select public.promote_item_comment($1,2)",[root]);
  await asUser(null);
  await denied(post,[archive,item,"Anonymous",null,"72000000-0000-4000-8000-000000000007"]);
  await asUser(users[4]);
  await q(change,[root,"restore","",3]);
  await q("select public.set_item_archived($1,true)",[item]);
  await denied(post,[archive,item,"Archived item",null,"72000000-0000-4000-8000-000000000008"]);
  // Existing deletion must accept the same-table reply FK and remove the whole thread atomically.
  const snap=await one("select public.item_management_snapshot($1) s",[item]);
  const deletion=(await one("select public.begin_item_deletion($1,$2,'DELETE') d",[item,snap.s.version])).d;
  await asOwner();
  await q("delete from storage.objects where name in (select storage_path from public.archive_item_files where item_id=$1)",[item]);
  await asUser(users[4]);
  await q("select public.finish_item_deletion($1)",[deletion.id]);
  eq((await one("select count(*)::int n from public.comments where item_id=$1",[item])).n,0);
  await asOwner();
  await q("update public.archive_memberships set role=$1 where archive_id=$2 and profile_id=$3",[previousRole,archive,users[2]]);
  await asUser(users[4]);
  console.log(`Conversation assertions passed: ${checks}; permission denials counted in main suite.`);
  return checks;
}
